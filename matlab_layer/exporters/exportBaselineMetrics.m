function outPath = exportBaselineMetrics(outPath)
%EXPORTBASELINEMETRICS Execute runCompleteEvaluationAndReport (cached fast path)
% and serialize Sections 1-6 into baseline_matlab_results/matlab_baseline_metrics.json
% conforming to traces/schemas/matlab_metrics_schema.json.

    exporterDir = fileparts(mfilename('fullpath'));
    matlabLayerDir = fileparts(exporterDir);
    workflowRoot = fileparts(matlabLayerDir);

    if nargin < 1 || isempty(outPath)
        outPath = fullfile(workflowRoot, 'baseline_matlab_results', 'matlab_baseline_metrics.json');
    end

    addpath(genpath(matlabLayerDir));
    report = runCompleteEvaluationAndReport('production', false, false);

    dt = report.dtHsbp;
    ca = report.contribA;
    cb = report.contribB;
    ov = report.overall;
    et = report.etaData;
    bt = report.batchData;

    payload = struct();
    payload.meta = struct( ...
        'generatedAt', char(datetime('now', 'Format', 'yyyy-MM-dd''T''HH:mm:ss')), ...
        'sourceScript', 'runCompleteEvaluationAndReport.m', ...
        'etaBaseline', dt.eta);

    payload.section1_dthsbp = struct( ...
        'swarmSizes', round(dt.swarmSizes(:).'), ...
        'eta', dt.eta, ...
        'leaveBytes', struct( ...
            'FlatSBP', dt.leaveBytes.FlatSBP(:).', ...
            'HSBP', dt.leaveBytes.HSBP(:).', ...
            'DTHSBP', dt.leaveBytes.DTHSBP(:).', ...
            'DTHSBP_ideal', dt.leaveBytesIdeal.DTHSBP(:).'), ...
        'leaveMessages', struct( ...
            'FlatSBP', dt.leaveMessages.FlatSBP(:).', ...
            'HSBP', dt.leaveMessages.HSBP(:).', ...
            'DTHSBP', dt.leaveMessages.DTHSBP(:).', ...
            'DTHSBP_ideal', dt.leaveMessagesIdeal.DTHSBP(:).'), ...
        'leaveRekeyCount', struct( ...
            'FlatSBP', dt.leaveRekeyCount.FlatSBP(:).', ...
            'HSBP', dt.leaveRekeyCount.HSBP(:).', ...
            'DTHSBP', dt.leaveRekeyCount.DTHSBP(:).', ...
            'DTHSBP_ideal', dt.leaveRekeyCountIdeal.DTHSBP(:).'), ...
        'joinBytes', struct( ...
            'FlatSBP', dt.joinBytes.FlatSBP(:).', ...
            'HSBP', dt.joinBytes.HSBP(:).', ...
            'DTHSBP', dt.joinBytes.DTHSBP(:).'), ...
        'joinLeaderTimeMs', struct( ...
            'FlatSBP', dt.joinLeaderTime.FlatSBP(:).', ...
            'HSBP', dt.joinLeaderTime.HSBP(:).', ...
            'DTHSBP', dt.joinLeaderTime.DTHSBP(:).'), ...
        'leaveLeaderTimeMs', struct( ...
            'FlatSBP', dt.leaveLeaderTime.FlatSBP(:).', ...
            'HSBP', dt.leaveLeaderTime.HSBP(:).', ...
            'DTHSBP', dt.leaveLeaderTime.DTHSBP(:).'), ...
        'byteReductionVsHSBP', dt.byteReductionVsHSBP(:).', ...
        'byteReductionVsFlat', dt.byteReductionVsFlat(:).');

    payload.section2_contribA = struct( ...
        'clusterSizes', round(ca.clusterSizes(:).'), ...
        'batchSizes', round(ca.batchSizes(:).'), ...
        'eta', ca.eta, ...
        'unsortedExponentiations', ca.unsortedExponentiations, ...
        'sortedExponentiations', ca.sortedExponentiations, ...
        'unsortedTimeMs', ca.unsortedTimeMs, ...
        'sortedTimeMs', ca.sortedTimeMs, ...
        'avgExponentiationSavingPct', ca.avgExponentiationSavingPct);

    payload.section3_contribB = struct( ...
        'clusterSizes', round(cb.clusterSizes(:).'), ...
        'eta', cb.eta, ...
        'reactiveLeaderTimeMs', cb.reactiveLeaderTimeMs(:).', ...
        'precomputedLeaderTimeMs', cb.precomputedLeaderTimeMs(:).', ...
        'expectedLeaderTimeMs', cb.expectedLeaderTimeMs(:).', ...
        'latencyReductionPct', cb.latencyReductionPct(:).', ...
        'avgLatencyReductionPct', cb.avgLatencyReductionPct, ...
        'speedupFactor', cb.speedupFactor);

    s4 = struct( ...
        'swarmSizeN', 3000, ...
        'clusterSizeNc', 600, ...
        'eta', 0.85);
    s4.paradigms = cellstr(ov.paradigms(:).');
    s4.communicationBytes = ov.communicationBytes(:).';
    s4.leaderTimeMs = ov.leaderTimeMs(:).';
    s4.keysStoredPerMember = round(ov.keysStoredPerMember(:).');
    s4.intermediateExponentiations = ov.intermediateExponentiations(:).';
    s4.commReductionVsHSBP = ov.commReductionVsHSBP;
    s4.commReductionVsFlat = ov.commReductionVsFlat;
    s4.latencyReductionVsHSBP = ov.latencyReductionVsHSBP;
    s4.latencyReductionVsFlat = ov.latencyReductionVsFlat;
    payload.section4_overall = s4;

    payload.section5_etaSweep = struct( ...
        'clusterN', round(et.clusterN), ...
        'eta', et.eta(:).', ...
        'dtHsbpBytes', et.dtHsbpBytes(:).', ...
        'dtHsbpMessages', et.dtHsbpMessages(:).', ...
        'hsbpBytes', et.hsbpBytes(:).', ...
        'lkhBytes', et.lkhBytes(:).', ...
        'baselineEta', et.baselineEta, ...
        'baselineDtBytes', et.baselineDtBytes, ...
        'baselineSavingVsHSBP', et.baselineSavingVsHSBP, ...
        'baselineSavingVsLKH', et.baselineSavingVsLKH);

    payload.section6_batchScalability = struct( ...
        'clusterN', round(bt.clusterN), ...
        'mValues', round(bt.M(:).'), ...
        'DT_HSBP', struct( ...
            'messages', bt.DT_HSBP.messages(:).', ...
            'bytes', bt.DT_HSBP.bytes(:).', ...
            'leaderMs', bt.DT_HSBP.leaderMs(:).'), ...
        'HSBP', struct( ...
            'messages', bt.HSBP.messages(:).', ...
            'bytes', bt.HSBP.bytes(:).', ...
            'leaderMs', bt.HSBP.leaderMs(:).'), ...
        'LKH', struct( ...
            'messages', bt.LKH.messages(:).', ...
            'bytes', bt.LKH.bytes(:).', ...
            'leaderMs', bt.LKH.leaderMs(:).'));

    outDir = fileparts(outPath);
    if ~exist(outDir, 'dir')
        mkdir(outDir);
    end

    jsonStr = jsonencode(payload, 'PrettyPrint', true);
    fid = fopen(outPath, 'w', 'n', 'UTF-8');
    if fid == -1
        error('exportBaselineMetrics:FileOpenFailed', 'Cannot open %s for writing.', outPath);
    end
    cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
    fwrite(fid, jsonStr, 'char');
    fprintf('Exported MATLAB baseline metrics JSON: %s\n', outPath);
end
